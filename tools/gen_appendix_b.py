def chapter_equations() -> dict:
    txt = ""
    for f in sorted(glob.glob(str(ROOT / "chapters" / "**" / "*.qmd"), recursive=True)):
        txt += Path(f).read_text(encoding="utf-8") + "\n"
    pat = re.compile(r"\$\$\n((?:(?!\$\$).)*?)\n\$\$ \{#(eq-ch\d\d-[a-z0-9-]+)\}", re.S)
    return {m.group(2): m.group(1) for m in pat.finditer(txt)}


